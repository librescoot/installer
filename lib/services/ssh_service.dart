  /// Put the coordinator in place, saving a user's own onboot.sh if one is
  /// there.
  ///
  /// Two markers are checked, not one. Our own shim is the obvious case. The
  /// other is a board an installer from before the coordinator touched: those
  /// wrote their post-reboot half straight to this path, and saving one as if
  /// it were the user's script means handing it back on retirement, which
