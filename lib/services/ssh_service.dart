  /// Reboot the device
  Future<void> reboot() async {
    // No guard: every command here goes through runCommand, which reconnects
    // a dropped client itself.
    final rebootCommands = <String>[
      'reboot',
      '/sbin/reboot',
      'busybox reboot',
      'shutdown -r now',
    ];

    var requested = false;
    final misses = <String>[];
    for (final cmd in rebootCommands) {
      try {
        debugPrint('SSH: sending reboot command: $cmd');
        await runCommand(cmd, replayOnDisconnect: false);
        debugPrint('SSH: reboot command accepted: $cmd');
        requested = true;
        break;
      } catch (e) {
        final error = e.toString().toLowerCase();
        if (_looksLikeDisconnect(error)) {
          debugPrint('SSH: reboot likely triggered (connection dropped): $cmd');
          requested = true;
          break;
        }
        // Each entry covers a different image, so most runs miss the first
        // few. Only an exhausted list is a failure, and saying so per rung
        // sends whoever reads the log after a real fault to the wrong place.
        misses.add('$cmd -> $e');
        debugPrint('SSH: reboot command not available: $cmd');
      }
    }

    if (!requested) {
      throw Exception(
        'Failed to trigger reboot with known commands: ${misses.join('; ')}',
      );
    }

    debugPrint('SSH: disconnecting local SSH client after reboot attempt');
    disconnect();
  }

  bool _looksLikeDisconnect(String error) {
    return error.contains('connection reset') ||
        error.contains('broken pipe') ||
        error.contains('socket') ||
        error.contains('eof') ||
        error.contains('closed');
  }

  Future<Uint8List> _readToolAsset(String fileName) async {
    final bundleCandidates = <String>[
      'assets/tools/$fileName',
      'assets/binaries/$fileName',
    ];
    for (final candidate in bundleCandidates) {
      try {
        final data = await rootBundle.load(candidate);
        debugPrint('SSH: loaded tool asset from bundle: $candidate');
        return data.buffer.asUint8List(data.offsetInBytes, data.lengthInBytes);
      } catch (_) {
        // Try next candidate
      }
    }

    final candidates = <String>[
      path.join(Directory.current.path, 'assets', 'tools', fileName),
      path.join(Directory.current.path, 'assets', 'binaries', fileName),
      path.join(
        Platform.resolvedExecutable,
        '..',
        'data',
        'flutter_assets',
        'assets',
        'tools',
        fileName,
      ),
      path.join(
        Platform.resolvedExecutable,
        '..',
        'data',
        'flutter_assets',
        'assets',
        'binaries',
        fileName,
      ),
    ];

    for (final candidate in candidates) {
      final file = File(candidate);
      if (await file.exists()) {
        return file.readAsBytes();
      }
    }

    throw Exception('Required tool asset not found: $fileName');
  }

  String? _parseSerial(String raw) {
    final matches = RegExp(
      r'0x[0-9a-fA-F]+',
    ).allMatches(raw).map((m) => m.group(0)!).toList();
    if (matches.isNotEmpty) {
      return matches
          .map(
            (part) =>
                part.replaceFirst(RegExp(r'^0x', caseSensitive: false), ''),
          )
          .join()
          .toLowerCase();
    }
    // soc0/serial_number is a bare 16-digit uppercase hex word, no 0x prefix.
    final bare = RegExp(r'^[0-9a-fA-F]{16}$').firstMatch(raw.trim());
    return bare?.group(0)!.toLowerCase();
  }

