/// SSH connection info for a device
class DeviceInfo {
  final String host;
  final String firmwareVersion;
  final String? serialNumber;

  /// Value of ID= in /etc/os-release if known (e.g. 'librescoot-mdb').
  /// Used to distinguish Librescoot from stock when version numbers collide.
  final String? osId;

  DeviceInfo({
    required this.host,
    required this.firmwareVersion,
    this.serialNumber,
    this.osId,
  });
}

/// Callback used to obtain a manually-entered root password when neither the
/// empty password nor the bundled device-config credential authenticates.
/// [version] is the firmware version we believe the device is running (or
/// null if undetectable). [previousAttempts] is how many manual passwords
/// have already been tried this session. Return null/empty string to give up.
typedef ManualPasswordPrompt =
    Future<String?> Function({
      required String? version,
      required int previousAttempts,
    });

/// Service for SSH communication with MDB/DBC devices
class SshService {
  static const String mdbHost = '192.168.7.1';
  static const String dbcHost = '192.168.7.2';
  static const int sshPort = 22;
  static const String sshUser = 'root';
  /// Short on purpose. An attempt already in flight against an unreachable
  /// host cannot notice the host arriving, so a long timeout is a window in
  /// which a board that comes back is missed. On the local USB link a healthy
  /// connect completes in well under a second, so this only bounds failures,
  /// and the caller retries: shorter attempts more often cover a transient
  /// window strictly better than long ones for the same wall clock.
  static const Duration connectionTimeout = Duration(seconds: 5);
  static const int maxManualPasswordAttempts = 3;

