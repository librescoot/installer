  /// Re-establish the SSH session using the credentials that worked on the
  /// last successful [_connect]. Skips the post-auth setup (pm-stop, sftp
  /// check, version detect) since that state is already known. Concurrent
  /// callers share the same in-flight attempt.
  Future<void> _reconnect() async {
    final existing = _reconnectInFlight;
    if (existing != null) {
      await existing;
      return;
    }
    final attempt = _doReconnect();
    _reconnectInFlight = attempt;
    try {
      await attempt;
    } finally {
      _reconnectInFlight = null;
    }
  }

  Future<void> _doReconnect() async {
    final pw = _lastPassword;
    if (pw == null) {
      throw Exception('No prior connection to recover');
    }
    debugPrint('SSH: silent reconnect to $_lastHost');
    final socket = await SSHSocket.connect(
      _lastHost,
      sshPort,
      timeout: connectionTimeout,
    );
    final client = SSHClient(
      keepAliveInterval: const Duration(seconds: 5),
      socket,
      username: sshUser,
      onPasswordRequest: () => pw,
    );
    try {
      await client.authenticated;
    } catch (e) {
      client.close();
      rethrow;
    }
    _client = client;
    debugPrint('SSH: silent reconnect succeeded');
  }

  /// Upload a file to the device via SFTP with progress reporting.
  /// Falls back to cat-over-stdin if SFTP is unavailable.
  Future<void> uploadFile(
    Uint8List content,
    String remotePath, {
    void Function(int bytesSent, int totalBytes)? onProgress,
  }) async {
    await _ensureConnected('file upload');

    // Scale timeout with file size: at least 60s, plus 1s per 100KB
    final timeoutSecs = 60 + (content.length / (100 * 1024)).ceil();
    final timeout = Duration(seconds: timeoutSecs);

    if (_sftpAvailable) {
      try {
        await _uploadViaSftp(content, remotePath, onProgress).timeout(timeout);
      } catch (e) {
        debugPrint('SSH: SFTP upload failed ($e), falling back to cat');
        _sftpAvailable = false;
        // The SFTP attempt can spend the whole timeout before failing, which
        // is long enough for the session to have gone with it. The fallback
        // needs a client of its own rather than the one checked on entry.
        await _ensureConnected('upload fallback');
        await _uploadViaCat(content, remotePath).timeout(timeout);
      }
    } else {
      await _uploadViaCat(content, remotePath).timeout(timeout);
    }

    // Make executable if needed
    if (remotePath.endsWith('.sh') || remotePath.contains('fw_setenv')) {
      await runCommand('chmod +x $remotePath');
    }
  }

  Future<void> _uploadViaSftp(
    Uint8List content,
    String remotePath,
    void Function(int bytesSent, int totalBytes)? onProgress,
  ) async {
    final sftp = await _requireClient('SFTP upload').sftp();
    try {
      final file = await sftp.open(
        remotePath,
        mode:
            SftpFileOpenMode.write |
            SftpFileOpenMode.create |
            SftpFileOpenMode.truncate,
      );
      try {
        const chunkSize = 64 * 1024;
        final stream = Stream<Uint8List>.fromIterable(
          Iterable.generate((content.length + chunkSize - 1) ~/ chunkSize, (i) {
            final start = i * chunkSize;
            final end = (start + chunkSize).clamp(0, content.length);
            return Uint8List.sublistView(content, start, end);
          }),
        );

        final writer = file.write(
          stream,
          onProgress: (total) => onProgress?.call(total, content.length),
        );
        await writer.done;
      } finally {
        await file.close();
      }
    } finally {
      sftp.close();
    }
  }

  Future<void> _uploadViaCat(Uint8List content, String remotePath) async {
    final session = await _requireClient('upload').execute('cat > $remotePath');
    session.stdin.add(content);
    await session.stdin.close();
    // Drain stdout/stderr to prevent blocking
    final stdoutDone = () async {
      await for (final _ in session.stdout) {}
    }();
    final stderrDone = () async {
      await for (final _ in session.stderr) {}
    }();
    await Future.wait([stdoutDone, stderrDone, session.done]);
  }

  /// Upload fw_setenv and configure bootloader for mass storage mode
  Future<void> configureMassStorageMode() async {
    // No guard: every step here goes through runCommand or uploadFile, both
    // of which reconnect a dropped client themselves.

    // Check if the device already has fw_setenv and fw_env.config (Librescoot).
    // If so, use the device's own tools and config (correct env offsets).
    // If not (stock scooterOS), upload our bundled versions.
    final hasNativeFwSetenv =
        (await runCommand(
          'command -v fw_setenv >/dev/null 2>&1 && echo yes || echo no',
        )).trim() ==
        'yes';
    final hasNativeConfig =
        (await runCommand(
          'test -f /etc/fw_env.config && echo yes || echo no',
        )).trim() ==
        'yes';

    final String fwSetenvCmd;
    final String configFlag;

    if (hasNativeFwSetenv && hasNativeConfig) {
      debugPrint('SSH: using device-native fw_setenv and /etc/fw_env.config');
      fwSetenvCmd = 'fw_setenv';
      configFlag = '';
    } else {
      debugPrint('SSH: uploading bundled fw_setenv and fw_env.config');
      final fwSetenv = await _readToolAsset('fw_setenv');
      final fwEnvConfig = await _readToolAsset('fw_env.config');
      debugPrint('SSH: uploading fw_setenv (${fwSetenv.length} bytes)...');
      await uploadFile(fwSetenv, '/tmp/fw_setenv');
      debugPrint(
        'SSH: uploading fw_env.config (${fwEnvConfig.length} bytes)...',
      );
      await uploadFile(fwEnvConfig, '/tmp/fw_env.config');
      debugPrint('SSH: uploads complete');
      fwSetenvCmd = '/tmp/fw_setenv';
      configFlag = '-c /tmp/fw_env.config';
    }

    // Set bootloader variables for USB mass storage mode.
    // Some boards need fuse programming in bootcmd (legacy).
    // If that fails, fall back to plain UMS bootcmd.
    // Use single quotes so the remote shell passes semicolons through
    // to fw_setenv as a single value argument.
    //
    // This bootcmd stays until an image is written, and putting it back early
    // is not a courtesy but a hazard. UMS is the only state on this board
    // reachable without a working Linux: entering it needs fw_setenv, which
    // needs a booted rootfs. So a board parked here can always be flashed,
    // and a board taken out of here that then fails to boot cannot be brought
    // back without opening it up.
    //
    // Restoring the old bootcmd would also require knowing nothing has been
    // written yet, which is not knowable: another instance may have started a
    // write, and a partly written rootfs leaves an environment nobody should
    // trust. Once anything has been written the only guaranteed-correct state
    // is a complete image.
    //
    // A run abandoned at the flash screen therefore leaves the board in UMS on
    // purpose. Relaunching picks it straight back up, which is what
    // mdbDetectedUmsSkipping is for.
    final fullBootcmd =
        "$fwSetenvCmd $configFlag bootcmd 'fuse prog -y 0 5 0x00002860; "
        "fuse prog -y 0 6 0x00000010; ums 0 mmc 1'";
    final fallbackBootcmd = "$fwSetenvCmd $configFlag bootcmd 'ums 0 mmc 1'";

    try {
      debugPrint('SSH: running: $fullBootcmd');
      final result = await runCommand(fullBootcmd);
      debugPrint('SSH: fw_setenv bootcmd result: "$result"');
    } catch (e) {
      debugPrint('SSH: full bootcmd failed ($e), trying fallback...');
      final result = await runCommand(fallbackBootcmd);
      debugPrint('SSH: fallback fw_setenv result: "$result"');
    }

    // Give fw_setenv time to flush to eMMC
    await Future.delayed(const Duration(seconds: 2));

    final delayResult = await runCommand(
      '$fwSetenvCmd $configFlag bootdelay 0',
    );
    debugPrint('SSH: fw_setenv bootdelay result: "$delayResult"');

    // Give fw_setenv time to flush
    await Future.delayed(const Duration(seconds: 2));
    debugPrint('SSH: bootloader configured for mass storage mode');
  }

