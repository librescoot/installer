  /// Retries for a connection that dies before authentication ever happens.
  /// Doubling from one second, so the ladder spans about a minute: longer than
  /// any reboot this installer performs takes to bring sshd back.
  static const int maxPreAuthRetries = 15;

  /// Delay between attempts after a pre-auth drop.
  ///
  /// Constant, not a backoff. A pre-auth drop is a board whose sshd is
  /// listening before the system can authenticate, which is the ordinary state
  /// of every board this talks to for the first minute after a reboot. Backing
  /// off protects a server that is loaded, rate limiting or hostile, and this
  /// is a known device on a private link with nothing else on it. Doubling to
  /// 32 seconds meant the board could be ready for half a minute before anyone
  /// asked. A genuine auth failure is a different branch and does not come
  /// here.
  static const Duration preAuthRetryDelay = Duration(seconds: 2);

  /// Whether a failure hit the transport rather than the credential.
  ///
  /// dartssh2 raises [SSHAuthAbortError] when the connection closes before
  /// authentication completes, which is what sshd looks like in the seconds
  /// after a reboot. It arrives on the same path as a genuine rejection, so
  /// the two have to be told apart before the credential ladder advances.
  @visibleForTesting
  static bool isPreAuthDrop(Object e) {
    if (e is SSHAuthAbortError) return true;
    if (e is SocketException) return true;
    if (e is TimeoutException) return true;
    final text = e.toString();
    return text.contains('Connection closed before authentication') ||
        text.contains('Connection reset') ||
        text.contains('Software caused connection abort');
  }

  @visibleForTesting
  static Future<T> executeWithReplayPolicy<T>({
    required Future<T> Function() execute,
    required Future<void> Function() reconnect,
    required void Function() invalidateConnection,
    required bool Function(Object error) isDisconnect,
    bool replayOnDisconnect = false,
  }) async {
    try {
      return await execute();
    } catch (error) {
      if (!isDisconnect(error)) rethrow;
      invalidateConnection();
      if (!replayOnDisconnect) rethrow;
      await reconnect();
      try {
        return await execute();
      } catch (replayError) {
        if (isDisconnect(replayError)) invalidateConnection();
        rethrow;
      }
    }
  }

  SSHClient? _client;
  Map<String, String>? _deviceConfig;
  bool _sftpAvailable = false;

  /// How long the SFTP capability probe waits for a subsystem that may never
  /// answer. Short: a working one responds immediately, and the fallback is
  /// always available, so this is paid only to learn that it is needed.
  static const Duration sftpProbeTimeout = Duration(seconds: 8);
  ManualPasswordPrompt? _manualPasswordPrompt;

  // Snapshot of the last successful auth so we can silently re-establish the
  // session if the underlying socket dies (e.g. USB cable wiggle during a
  // poll loop). Cleared by [disconnect] so reboot paths don't auto-reconnect
  // before the device is back.
  String _lastHost = mdbHost;
  String? _lastPassword;
  Future<void>? _reconnectInFlight;
  int _redisQueueSequence = 0;

  /// Auth key injected at build time via --dart-define=AUTH_KEY=...
  static const _authKey = String.fromEnvironment('AUTH_KEY');

  /// Load device configuration from encrypted or plaintext asset.
  Future<void> loadDeviceConfig(String assetsPath) async {
    String yamlContent;

    if (_authKey.isNotEmpty) {
      try {
        final data = await rootBundle.load('$assetsPath/device_configs.bin');
        debugPrint('SSH: loading device profile (bundle)');
        yamlContent = _decryptAsset(
          data.buffer.asUint8List(data.offsetInBytes, data.lengthInBytes),
        );
      } catch (_) {
        final encFile = File(path.join(assetsPath, 'device_configs.bin'));
        if (await encFile.exists()) {
          debugPrint('SSH: loading device profile (filesystem)');
          yamlContent = _decryptAsset(await encFile.readAsBytes());
        } else {
          yamlContent = '';
        }
      }
    } else {
      yamlContent = '';
    }

    if (yamlContent.isEmpty) {
      final plainFile = File(path.join(assetsPath, 'device_configs.yml'));
      if (await plainFile.exists()) {
        debugPrint('SSH: loading device profile (dev fallback)');
        yamlContent = await plainFile.readAsString();
      } else {
        debugPrint('SSH: no device profile available, will use defaults');
        _deviceConfig = {};
        return;
      }
    }

    final yaml = loadYaml(yamlContent) as YamlMap;
    _deviceConfig = {};
    for (final entry in yaml.entries) {
      final version = entry.key.toString();
      final encoded = entry.value.toString();
      final decodedRaw = utf8.decode(base64.decode(encoded));
      _deviceConfig![version] = decodedRaw.trim();
    }
    debugPrint('SSH: device profile loaded (${_deviceConfig!.length} entries)');
  }

  /// Decrypt AES-256-CBC with IV prepended, PKCS7 padding.
  String _decryptAsset(Uint8List encrypted) {
    final keyBytes = Uint8List.fromList(
      utf8.encode(_authKey).take(32).toList()
        ..addAll(List.filled(32 - _authKey.length.clamp(0, 32), 0)),
    );
    final iv = encrypted.sublist(0, 16);
    final ciphertext = encrypted.sublist(16);

    final cipher = pc.CBCBlockCipher(pc.AESEngine())
      ..init(false, pc.ParametersWithIV(pc.KeyParameter(keyBytes), iv));

    final padded = Uint8List(ciphertext.length);
    var offset = 0;
    while (offset < ciphertext.length) {
      offset += cipher.processBlock(ciphertext, offset, padded, offset);
    }

    // Remove PKCS7 padding
    final padLen = padded.last;
    final unpadded = padded.sublist(0, padded.length - padLen);

    return utf8.decode(unpadded);
  }

  /// Set a callback to be invoked when the bundled credentials don't work
  /// and we need to ask the user for the root password. Only the initial
  /// MDB connect on stock firmware needs this: once Librescoot is flashed
  /// the password is empty.
  void setManualPasswordPrompt(ManualPasswordPrompt? prompt) {
    _manualPasswordPrompt = prompt;
  }

  /// Connect to MDB and detect firmware version
  Future<DeviceInfo> connectToMdb() async {
    final info = await _connect(mdbHost);
    // The MDB has no reliable RTC, so its clock (and every log timestamp)
    // drifts to nonsense across power cycles. Push the host's wall-clock time
    // and timezone in now that we have a shell. Best-effort, never fatal.
    await syncDeviceTime();
    return info;
  }

  /// Set the connected device's clock + timezone from this host. Best-effort:
  /// failures are logged and swallowed so a missing `hwclock`/`timedatectl`
  /// never blocks the install.
  Future<void> syncDeviceTime() async {
    if (_client == null) return;
    try {
      final utc = DateTime.now().toUtc();
      String two(int v) => v.toString().padLeft(2, '0');
      final stamp =
          '${utc.year.toString().padLeft(4, '0')}-${two(utc.month)}-${two(utc.day)} '
          '${two(utc.hour)}:${two(utc.minute)}:${two(utc.second)}';
      final tz = _hostTimezone();
      final cmds = <String>[];
      if (tz != null) {
        cmds.add(
          'timedatectl set-timezone $tz 2>/dev/null || ln -sf /usr/share/zoneinfo/$tz /etc/localtime 2>/dev/null || true',
        );
      }
      // -u: interpret the stamp as UTC, independent of the device's timezone.
      cmds.add('date -u -s "$stamp" >/dev/null 2>&1 || true');
      cmds.add('hwclock -w -u 2>/dev/null || true');
      // 60s, not 15: a freshly flashed board is busy on its first boot and
      // has been seen taking a minute just to offer SFTP. A clock that is
      // wrong on a board about to write date-stamped logs is worth waiting
      // for, and this is best-effort anyway.
      await runCommand(cmds.join('; '), timeout: const Duration(seconds: 60));
      debugPrint(
        'SSH: synced device time to ${stamp}Z, tz=${tz ?? '(unknown)'}',
      );
    } catch (e) {
      debugPrint('SSH: device time sync failed (non-fatal): $e');
    }
  }

  /// Best-effort IANA timezone of this host (e.g. "Europe/Berlin"), read from
  /// the /etc/localtime symlink. Returns null on Windows or if undeterminable.
  String? _hostTimezone() {
    try {
      if (Platform.isWindows) return null;
      final link = Link('/etc/localtime');
      if (link.existsSync()) {
        final target = link.targetSync();
        const marker = 'zoneinfo/';
        final i = target.indexOf(marker);
        if (i >= 0) {
          final tz = target.substring(i + marker.length);
          if (tz.isNotEmpty && !tz.contains(' ')) return tz;
        }
      }
    } catch (_) {}
    return null;
  }

  /// Connect to DBC via MDB jump host
  Future<DeviceInfo> connectToDbc() async {
    // First ensure we're connected to MDB
    if (_client == null) {
      await connectToMdb();
    }

    // Connect to DBC through MDB
    return _connect(dbcHost);
  }

  Future<DeviceInfo> _connect(String host) async {
    // Auth strategy:
    //   1. empty password (Librescoot)
    //   2. bundled credential matched against banner version (stock OS)
    //   3. user-supplied password via manual prompt callback (unknown stock)
    var authVersion = 'v1.20';
    var stage = 0; // 0 = empty, 1 = bundled, 2 = manual
    var manualAttempts = 0;
    var preAuthRetries = 0;
    String? manualPassword;

    while (true) {
      final socket = await SSHSocket.connect(
        host,
        sshPort,
        timeout: connectionTimeout,
      );
      debugPrint('SSH: connected socket to $host:$sshPort');

      var bannerVersionSeen = authVersion;
      String? attemptedPassword;
      _client = SSHClient(
        socket,
        username: sshUser,
        // Idle for minutes at a time while the user pairs a phone or teaches
        // in keycards; without this the far end can drop the session and the
        // next command fails for no visible reason.
        keepAliveInterval: const Duration(seconds: 5),
        onPasswordRequest: () {
          String pw;
          if (stage == 0) {
            debugPrint('SSH: attempting default device configuration');
            pw = '';
          } else if (stage == 1) {
            // Stage 0 already verified this version has a non-empty bundled
            // credential before transitioning here.
            pw = _resolveDeviceCredential(authVersion);
            debugPrint(
              'SSH: attempting bundled device configuration for version $authVersion',
            );
          } else {
            debugPrint(
              'SSH: attempting user-supplied configuration (attempt $manualAttempts)',
            );
            pw = manualPassword ?? '';
          }
          attemptedPassword = pw;
          return pw;
        },
        onUserauthBanner: (banner) {
          final bannerVersion = _extractVersionFromText(banner);
          if (bannerVersion != null) {
            bannerVersionSeen = bannerVersion;
            authVersion = bannerVersion;
            debugPrint('SSH: parsed version from banner -> $authVersion');
          }
        },
      );

      try {
        // dartssh2 completes this when the handshake finishes and never if the
        // far end accepts the socket and then says nothing. Without a bound
        // that is an unrecoverable hang rather than a failure: the retry below
        // only sees exceptions, so a stalled handshake never reaches it and
        // the screen sits on "reconnecting" for as long as anyone waits.
        await _client!.authenticated.timeout(connectionTimeout);
        debugPrint('SSH: authentication successful');
        _lastHost = host;
        _lastPassword = attemptedPassword ?? '';
        break;
      } catch (e) {
        debugPrint('SSH: authentication failed: $e');
        _client?.close();
        _client = null;

        // Not a rejected credential: a host that is not answering yet. Hold
        // the stage and the password where they are and come back.
        if (isPreAuthDrop(e) && preAuthRetries < maxPreAuthRetries) {
          preAuthRetries++;
          debugPrint(
            'SSH: dropped before authentication, retry '
            '$preAuthRetries/$maxPreAuthRetries in '
            '${preAuthRetryDelay.inSeconds}s',
          );
          await Future.delayed(preAuthRetryDelay);
          continue;
        }

        if (stage == 0) {
          if (bannerVersionSeen != 'v1.20') {
            authVersion = bannerVersionSeen;
            // Skip stage 1 if the bundled lookup would just return empty
            // (which we already tried) or has no entry at all.
            String? bundled;
            try {
              bundled = _resolveDeviceCredential(authVersion);
            } catch (_) {
              bundled = null;
            }
            if (bundled != null && bundled.isNotEmpty) {
              stage = 1;
              debugPrint(
                'SSH: default configuration not accepted, attempting bundled device configuration for $authVersion',
              );
              continue;
            }
            debugPrint(
              'SSH: no bundled device configuration for $authVersion, prompting user',
            );
          }
          stage = 2;
        } else if (stage == 1) {
          stage = 2;
        }

        if (stage == 2 &&
            _manualPasswordPrompt != null &&
            manualAttempts < maxManualPasswordAttempts) {
          final entered = await _manualPasswordPrompt!(
            version: bannerVersionSeen != 'v1.20' ? bannerVersionSeen : null,
            previousAttempts: manualAttempts,
          );
          if (entered == null || entered.isEmpty) {
            debugPrint('SSH: user cancelled manual configuration prompt');
            rethrow;
          }
          manualPassword = entered;
          manualAttempts++;
          debugPrint(
            'SSH: retrying with user-supplied configuration (attempt $manualAttempts)',
          );
          continue;
        }

        rethrow;
      }
    }

    // Stop power manager to prevent suspend/hibernate during flashing
    try {
      await runCommand(
        'systemctl stop librescoot-pm 2>/dev/null; '
        'systemctl stop unu-pm 2>/dev/null; true',
      );
      debugPrint('SSH: stopped power manager');
    } catch (_) {}

    final detected = await _detectFirmwareVersion();
    if (detected.version != null) {
      authVersion = detected.version!;
      debugPrint(
        'SSH: detected firmware version ${detected.version}'
        '${detected.osId != null ? " (os-id=${detected.osId})" : ""}',
      );
    } else {
      debugPrint(
        'SSH: firmware version detection failed, using Unknown for UI',
      );
    }

    // Stock runs dropbear, which has no working sftp subsystem, and os-release
    // has just told us which distribution this is. Skipping the probe outright
    // is better than probing well: the answer is already known and the probe
    // costs a timeout to reach it.
    final osId = detected.osId ?? '';
    if (osId.isNotEmpty && !osId.startsWith('librescoot')) {
      _sftpAvailable = false;
      debugPrint('SSH: os-release ID "$osId", uploads will use cat');
    } else {
      // Write something, do not just open a session. Neither the sftp-server
      // binary being on disk nor a session opening says the subsystem works:
      // dropbear opens one and then never completes a write, so an
      // open-and-close probe reported available and every upload afterwards
      // spent its full timeout discovering otherwise.
      //
      // A few bytes to /tmp is the smallest operation that exercises the thing
      // that actually fails, and the file is removed on the way out.
      try {
        final sftp = await _requireClient(
          'SFTP probe',
        ).sftp().timeout(sftpProbeTimeout);
        try {
          const probePath = '/tmp/.installer-sftp-probe';
          final file = await sftp
              .open(
                probePath,
                mode:
                    SftpFileOpenMode.write |
                    SftpFileOpenMode.create |
                    SftpFileOpenMode.truncate,
              )
              .timeout(sftpProbeTimeout);
          try {
            await file
                .write(Stream.value(Uint8List.fromList([0x6f, 0x6b])))
                .done
                .timeout(sftpProbeTimeout);
          } finally {
            await file.close();
          }
          await sftp.remove(probePath).timeout(sftpProbeTimeout);
          _sftpAvailable = true;
          debugPrint('SSH: SFTP available');
        } finally {
          sftp.close();
        }
      } catch (e) {
        _sftpAvailable = false;
        debugPrint('SSH: SFTP not available ($e), uploads will use cat');
      }
    }

    // Get serial number
    String? serial;
    try {
      // OCOTP UID is (CFG1 << 32) | CFG0 — high word first when concatenated.
      // fsl_otp is the NXP vendor driver (stock 4.x and librescoot 5.4
      // kernels); mainline kernels (1.2.0+ MDBs on linux-fslc 6.12) expose
      // the same value preformatted at /sys/devices/soc0/serial_number.
      final result = await runCommand(
        'cat /sys/fsl_otp/HW_OCOTP_CFG1 /sys/fsl_otp/HW_OCOTP_CFG0 2>/dev/null'
        ' || cat /sys/devices/soc0/serial_number 2>/dev/null',
      );
      serial = _parseSerial(result);
      if (serial != null) {
        debugPrint('SSH: parsed serial $serial');
      }
    } catch (e) {
      debugPrint('SSH: serial read failed: $e');
    }

    return DeviceInfo(
      host: host,
      firmwareVersion: detected.version ?? 'Unknown',
      serialNumber: serial,
      osId: detected.osId,
    );
  }

  Future<({String? version, String? osId})> _detectFirmwareVersion() async {
    if (_client == null) return (version: null, osId: null);

    final versionIdRegex = RegExp(
      r'^VERSION_ID="?([^"\n]+)"?$',
      multiLine: true,
    );
    final idRegex = RegExp(r'^ID="?([^"\n]+)"?$', multiLine: true);
    final semverRegex = RegExp(r'\bv?(\d+\.\d+(?:\.\d+)?)\b');

    final commands = <String>[
      'cat /etc/os-release 2>/dev/null',
      'cat /etc/librescoot-release 2>/dev/null',
      'cat /etc/issue 2>/dev/null',
    ];

    for (final command in commands) {
      try {
        debugPrint('SSH: checking firmware version via `$command`');
        final output = await runCommand(command);

        final idMatch = idRegex.firstMatch(output);
        final osId = idMatch?.group(1)?.trim();

        final versionIdMatch = versionIdRegex.firstMatch(output);
        if (versionIdMatch != null) {
          final version = _normalizeVersion(versionIdMatch.group(1)!);
          debugPrint('SSH: parsed VERSION_ID -> $version');
          return (version: version, osId: osId);
        }

        final semverMatch = semverRegex.firstMatch(output);
        if (semverMatch != null) {
          final version = _normalizeVersion(semverMatch.group(1)!);
          debugPrint('SSH: parsed semver -> $version');
          return (version: version, osId: osId);
        }

        debugPrint('SSH: no version match from command output');
      } catch (e) {
        debugPrint('SSH: command failed during version detection: $e');
        continue;
      }
    }

    return (version: null, osId: null);
  }

  String _normalizeVersion(String raw) {
    final trimmed = raw.trim();
    // Only add 'v' prefix for semver-like versions (e.g. 1.15.0), not channel tags
    if (trimmed.startsWith('v') || !RegExp(r'^\d').hasMatch(trimmed)) {
      return trimmed;
    }
    return 'v$trimmed';
  }

  String? _extractVersionFromText(String text) {
    final match = RegExp(r'\bv?(\d+\.\d+(?:\.\d+)?)\b').firstMatch(text);
    if (match == null) return null;
    return _normalizeVersion(match.group(1)!);
  }

  double _versionToNumber(String version) {
    final clean = version.trim().toLowerCase().replaceFirst('v', '');
    final parts = clean.split('.');
    final major = parts.isNotEmpty ? int.tryParse(parts[0]) ?? 0 : 0;
    final minor = parts.length > 1 ? int.tryParse(parts[1]) ?? 0 : 0;
    final patch = parts.length > 2 ? int.tryParse(parts[2]) ?? 0 : 0;
    return (major * 1000000) + (minor * 1000) + patch.toDouble();
  }

  String _resolveDeviceCredential(String version) {
    if (_deviceConfig == null || _deviceConfig!.isEmpty) {
      debugPrint(
        'SSH: no device profile available, using default configuration',
      );
      return '';
    }

    final normalized = _normalizeVersion(version);
    debugPrint('SSH: resolving device configuration for version "$version"');

    // Try exact match first
    if (_deviceConfig!.containsKey(normalized)) {
      return _deviceConfig![normalized]!;
    }
    if (_deviceConfig!.containsKey(version)) {
      return _deviceConfig![version]!;
    }
    final withoutV = normalized.replaceFirst('v', '');
    if (_deviceConfig!.containsKey(withoutV)) {
      return _deviceConfig![withoutV]!;
    }

    final parts = withoutV.split('.');
    if (parts.length == 3) {
      final majorMinor = 'v${parts[0]}.${parts[1]}';
      if (_deviceConfig!.containsKey(majorMinor)) {
        return _deviceConfig![majorMinor]!;
      }
    }

    // Try to find closest version
    final versionNum = _versionToNumber(normalized);
    String? closestVersion;
    double closestDiff = double.infinity;

    for (final key in _deviceConfig!.keys) {
      final keyNum = _versionToNumber(key);
      final diff = (keyNum - versionNum).abs();
      if (diff < closestDiff) {
        closestDiff = diff;
        closestVersion = key;
      }
    }

    if (closestVersion != null) {
      debugPrint('SSH: using closest profile entry "$closestVersion"');
      return _deviceConfig![closestVersion]!;
    }

    throw Exception('No device config found for version $version');
  }

  /// Rebuild a dropped client, or throw naming [operation].
  ///
  /// _lastPassword survives everything except an explicit disconnect(), so a
  /// client lost to an idle timeout or to invalidateConnection can be rebuilt
  /// without asking the user again.
  /// The live client, or a failure that says which operation lost it.
  ///
  /// The alternative is `_client!`, which reports a null-assertion with no
  /// indication of what was being attempted. Callers that can reconnect should
  /// go through [_ensureConnected] first; this is for the point of use.
  SSHClient _requireClient(String operation) {
    final client = _client;
    if (client == null) {
      throw Exception('SSH session lost during $operation');
    }
    return client;
  }

  /// Re-establish the session if it is gone, for a caller that wants the
  /// reconnect to happen at a point it can show rather than lazily inside the
  /// next upload.
  Future<void> ensureConnected(String operation) => _ensureConnected(operation);

  Future<void> _ensureConnected(String operation) async {
    if (_client != null) return;
    if (_lastPassword == null) {
      throw Exception(
        'SSH session lost before $operation, with no stored credential to '
        'resume it.',
      );
    }
    debugPrint('SSH: client gone, reconnecting for $operation');
    await _reconnect();
  }

  /// Run a command on the connected device.
  Future<String> runCommand(
    String command, {
    Duration timeout = const Duration(seconds: 60),
    bool replayOnDisconnect = false,
  }) async {
    await _ensureConnected('command');

    return executeWithReplayPolicy(
      execute: () => _runCommandOnce(command, timeout),
      reconnect: () async {
        debugPrint('SSH: replay-safe command disconnected, reconnecting once');
        await _reconnect();
      },
      invalidateConnection: () {
        _client?.close();
        _client = null;
      },
      isDisconnect: (error) =>
          _looksLikeDisconnect(error.toString().toLowerCase()),
      replayOnDisconnect: replayOnDisconnect && _lastPassword != null,
    );
  }

  Future<String> _runCommandOnce(String command, Duration timeout) async {
    final session = await _requireClient('command').execute(command);
    final stdout = StringBuffer();
    final stderr = StringBuffer();

    final stdoutDone = () async {
      await for (final data in session.stdout) {
        stdout.write(utf8.decode(data));
      }
    }();

    final stderrDone = () async {
      await for (final data in session.stderr) {
        stderr.write(utf8.decode(data));
      }
    }();

    try {
      await Future.wait([
        stdoutDone,
        stderrDone,
        session.done,
      ]).timeout(timeout);
    } catch (_) {
      // A timed-out session stays open otherwise, and every stalled command
      // costs another channel until the connection hits its limit and stops
      // accepting new ones.
      session.close();
      rethrow;
    }

    final exitCode = session.exitCode;
    if (exitCode != null && exitCode != 0) {
      throw Exception(
        'Command failed (exit $exitCode): $command'
        '${stderr.isNotEmpty ? '\nstderr: ${stderr.toString().trim()}' : ''}',
      );
    }

    return stdout.toString();
  }

  /// Run [command], handing stdout and stderr to the callbacks as the bytes
  /// arrive. Unlike [runCommand] this returns the exit code instead of
  /// throwing, because callers here want to distinguish mender's own failure
  /// from a transport failure and want its stderr verbatim.
  ///
  /// [timeout] has to cover a full artifact install, which writes several
  /// hundred megabytes to eMMC on a slow SoC.
  Future<({int exitCode, String stdout, String stderr})> runStreaming(
    String command, {
    void Function(String chunk)? onStdout,
    void Function(String chunk)? onStderr,
    Duration timeout = const Duration(minutes: 30),
  }) async {
    if (_client == null) {
      if (_lastPassword == null) throw Exception('Not connected');
      await _reconnect();
    }

    final session = await _requireClient('streaming command').execute(command);
    final stdout = StringBuffer();
    final stderr = StringBuffer();

    final stdoutDone = () async {
      await for (final data in session.stdout) {
        final chunk = utf8.decode(data, allowMalformed: true);
        stdout.write(chunk);
        onStdout?.call(chunk);
      }
    }();
    final stderrDone = () async {
      await for (final data in session.stderr) {
        final chunk = utf8.decode(data, allowMalformed: true);
        stderr.write(chunk);
        onStderr?.call(chunk);
      }
    }();

    // A timeout used to throw straight out of here, leaving the session open,
    // the remote command running and both drain futures pending. A retry then
    // started a second mender-update install against a board where the first
    // still held the lock. SIGTERM first so mender gets a chance to unwind,
    // then close the channel either way; killing the session ends both
    // streams, which is what lets the drains finish.
    try {
      await Future.wait([
        stdoutDone,
        stderrDone,
        session.done,
      ]).timeout(timeout);
    } catch (e) {
      try {
        session.kill(SSHSignal.TERM);
      } catch (killError) {
        debugPrint('SSH: could not signal the remote command: $killError');
      }
      session.close();
      // The drains are still listening on streams that are about to end.
      // Swallow whatever they finish with: the error being reported is [e],
      // and an unhandled one from here would take the isolate down instead.
      unawaited(stdoutDone.catchError((_) {}));
      unawaited(stderrDone.catchError((_) {}));
      rethrow;
    }

    return (
      exitCode: session.exitCode ?? -1,
      stdout: stdout.toString(),
      stderr: stderr.toString(),
    );
  }

