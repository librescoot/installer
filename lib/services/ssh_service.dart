  /// Download a remote file's contents via cat. Returns null if the file doesn't exist.
  Future<Uint8List?> downloadFile(String remotePath) async {
    await _ensureConnected('file download');
    SSHSession? session;
    try {
      session = await _requireClient(
        'file download',
      ).execute('cat ${_shellEscape(remotePath)}');
      final chunks = <int>[];
      final stdoutDone = () async {
        await for (final data in session!.stdout) {
          chunks.addAll(data);
        }
      }();
      // Must drain stderr to prevent the session from blocking
      final stderrDone = () async {
        await for (final _ in session!.stderr) {}
      }();
      await Future.wait([
        stdoutDone,
        stderrDone,
        session.done,
      ]).timeout(const Duration(seconds: 30));
      if (session.exitCode != 0) return null;
      return Uint8List.fromList(chunks);
    } catch (_) {
      // Swallowing the error is deliberate (a missing file is a null), but the
      // session has to go regardless: a timeout here otherwise leaks a channel
      // per attempt.
      session?.close();
      return null;
    }
  }

  /// List files in a remote directory. Returns empty list if directory doesn't exist.
  Future<List<String>> listRemoteDir(String remotePath) async {
    try {
      final output = await runCommand(
        'ls -1 ${_shellEscape(remotePath)} 2>/dev/null',
      );
      return output.trim().split('\n').where((l) => l.isNotEmpty).toList();
    } catch (_) {
      return [];
    }
  }

  static String _shellEscape(String s) => "'${s.replaceAll("'", "'\\''")}'";

  /// Back up radio-gaga config from the MDB to a local directory.
  /// Checks both Librescoot (/data/radio-gaga/) and stock (/etc/rescoot/) paths.
  /// Returns the backup directory path, or null if no config was found.
  Future<String?> backupRadioGagaConfig(String backupBaseDir) async {
    final timestamp = DateTime.now()
        .toIso8601String()
        .replaceAll(':', '-')
        .split('.')
        .first;
    final backupDir = Directory(
      path.join(backupBaseDir, 'radio-gaga-backup-$timestamp'),
    );

    var found = false;

    // Librescoot path: /data/radio-gaga/config.yaml + any referenced certs
    final lsConfig = await downloadFile('/data/radio-gaga/config.yaml');
    if (lsConfig != null && lsConfig.isNotEmpty) {
      final targetDir = Directory(path.join(backupDir.path, 'data-radio-gaga'));
      await targetDir.create(recursive: true);
      await File(
        path.join(targetDir.path, 'config.yaml'),
      ).writeAsBytes(lsConfig);
      debugPrint('SSH: backed up /data/radio-gaga/config.yaml');
      found = true;

      // Also back up any referenced cert files
      try {
        final yamlStr = utf8.decode(lsConfig);
        final yaml = loadYaml(yamlStr);
        if (yaml is Map) {
          final mqtt = yaml['mqtt'];
          if (mqtt is Map) {
            final caCertPath = mqtt['ca_cert'] as String?;
            if (caCertPath != null && caCertPath.isNotEmpty) {
              final certData = await downloadFile(caCertPath);
              if (certData != null && certData.isNotEmpty) {
                final certFilename = path.basename(caCertPath);
                await File(
                  path.join(targetDir.path, certFilename),
                ).writeAsBytes(certData);
                debugPrint('SSH: backed up CA cert $caCertPath');
              }
            }
          }
        }
      } catch (e) {
        debugPrint('SSH: failed to parse LS config for cert paths: $e');
      }
    }

    // Stock scooterOS paths
    const stockPaths = [
      '/etc/rescoot/radio-gaga.yml',
      '/home/root/radio-gaga/radio-gaga.yml',
    ];
    for (final stockPath in stockPaths) {
      final stockConfig = await downloadFile(stockPath);
      if (stockConfig == null || stockConfig.isEmpty) continue;

      final targetDir = Directory(path.join(backupDir.path, 'etc-rescoot'));
      await targetDir.create(recursive: true);
      await File(
        path.join(targetDir.path, 'radio-gaga.yml'),
      ).writeAsBytes(stockConfig);
      debugPrint('SSH: backed up $stockPath');
      found = true;

      // Parse YAML to find referenced files (e.g. mqtt.ca_cert) and back those up too
      try {
        final yamlStr = utf8.decode(stockConfig);
        final yaml = loadYaml(yamlStr);
        if (yaml is Map) {
          final mqtt = yaml['mqtt'];
          if (mqtt is Map) {
            final caCertPath = mqtt['ca_cert'] as String?;
            if (caCertPath != null && caCertPath.isNotEmpty) {
              final certData = await downloadFile(caCertPath);
              if (certData != null && certData.isNotEmpty) {
                final certFilename = path.basename(caCertPath);
                await File(
                  path.join(targetDir.path, certFilename),
                ).writeAsBytes(certData);
                debugPrint('SSH: backed up CA cert $caCertPath');
              }
            }
          }
        }
      } catch (e) {
        debugPrint('SSH: failed to parse stock config for cert paths: $e');
      }
      break; // found one, no need to check others
    }

    if (!found) {
      debugPrint('SSH: no radio-gaga config found to back up');
      return null;
    }

    debugPrint('SSH: radio-gaga config backed up to ${backupDir.path}');
    return backupDir.path;
  }

  /// Restore a backed-up radio-gaga config to /data/radio-gaga/ on the MDB.
  /// Handles stock configs by rewriting ca_cert paths to /data/radio-gaga/.
  Future<bool> restoreRadioGagaConfig(String backupPath) async {
    final backupDir = Directory(backupPath);
    if (!await backupDir.exists()) return false;

    await runCommand('mkdir -p /data/radio-gaga');

    // Prefer Librescoot backup (already in the right format)
    final librescootDir = Directory(path.join(backupPath, 'data-radio-gaga'));
    if (await librescootDir.exists()) {
      for (final file in await librescootDir.list().toList()) {
        if (file is! File) continue;
        final filename = path.basename(file.path);
        final data = await file.readAsBytes();
        await uploadFile(
          Uint8List.fromList(data),
          '/data/radio-gaga/$filename',
        );
        debugPrint('SSH: restored /data/radio-gaga/$filename');
      }
      return true;
    }

    // Stock backup: needs path rewriting
    final stockDir = Directory(path.join(backupPath, 'etc-rescoot'));
    if (!await stockDir.exists()) return false;

    final configFile = File(path.join(stockDir.path, 'radio-gaga.yml'));
    if (!await configFile.exists()) return false;

    // Upload any non-YAML files first (certs, keys)
    for (final file in await stockDir.list().toList()) {
      if (file is! File) continue;
      final filename = path.basename(file.path);
      if (filename == 'radio-gaga.yml') continue;
      final data = await file.readAsBytes();
      await uploadFile(Uint8List.fromList(data), '/data/radio-gaga/$filename');
      debugPrint('SSH: restored /data/radio-gaga/$filename');
    }

    // Rewrite ca_cert path in the config and upload
    var configContent = await configFile.readAsString();
    try {
      final yaml = loadYaml(configContent);
      if (yaml is Map) {
        final mqtt = yaml['mqtt'];
        if (mqtt is Map) {
          final caCertPath = mqtt['ca_cert'] as String?;
          if (caCertPath != null && caCertPath.isNotEmpty) {
            final certFilename = path.basename(caCertPath);
            final newPath = '/data/radio-gaga/$certFilename';
            configContent = configContent.replaceAll(caCertPath, newPath);
            debugPrint('SSH: rewrote ca_cert path: $caCertPath → $newPath');
          }
        }
      }
    } catch (e) {
      debugPrint(
        'SSH: failed to rewrite cert paths, uploading config as-is: $e',
      );
    }

    await uploadFile(
      Uint8List.fromList(utf8.encode(configContent)),
      '/data/radio-gaga/config.yaml',
    );
    debugPrint(
      'SSH: restored /data/radio-gaga/config.yaml (converted from stock)',
    );
    return true;
  }

  /// Read the trampoline status file from MDB.
  Future<TrampolineStatus> readTrampolineStatus({String? expectedRunId}) async {
    try {
      TrampolineStatus? matchingStatus;
      final content = await runCommand(
        'cat /data/installer/trampoline-status 2>/dev/null',
      );
      if (content.trim().isNotEmpty) {
        final status = TrampolineStatus.parse(content);
        if (expectedRunId == null || status.runId == expectedRunId) {
          if (status.result != TrampolineResult.running &&
              status.result != TrampolineResult.unknown) {
            return status;
          }
          matchingStatus = status;
        }
      }

      final currentState = await runCommand(
        'cat $installerRunState 2>/dev/null || '
        'cat $legacyRunState 2>/dev/null; true',
      );
      if (currentState.trim().isNotEmpty) {
        final state = InstallRunState.parse(currentState);
        if (expectedRunId == null || state.runId == expectedRunId) {
          return state.toTrampolineStatus();
        }
      }
      if (matchingStatus != null) return matchingStatus;

      // The status file lives in the staging directory, and a device that
      // finished the install on its own sweeps that directory as its last act.
      // Its completion record is what survives, and a run that got far enough
      // to write one is a run that succeeded.
      final record = await runCommand(
        'cat $installerLastInstall 2>/dev/null || '
        'cat $legacyLastInstall 2>/dev/null',
      );
      if (record.trim().isNotEmpty) {
        final status = TrampolineStatus.parseCompletionRecord(record);
        if (expectedRunId == null) {
          if (status.result == TrampolineResult.success) return status;
        } else if (status.completedFor(expectedRunId)) {
          return status;
        }
      }
      return TrampolineStatus(result: TrampolineResult.unknown);
    } catch (_) {
      return TrampolineStatus(result: TrampolineResult.unknown);
    }
  }

  /// The run-state file both sides write: which stage the run reached, who
  /// wrote it last, and whether it ended. Null when the board has none.
  Future<InstallRunState?> readInstallRunState() async {
    try {
      final content = await runCommand(
        'cat $installerRunState 2>/dev/null || '
        'cat $legacyRunState 2>/dev/null; true',
      );
      if (content.trim().isEmpty) return null;
      return InstallRunState.parse(content);
    } catch (_) {
      return null;
    }
  }

  /// Whether a trampoline is running on the board right now.
  ///
  /// The state file says what the last write claimed, which is not the same
  /// thing: a run killed mid-stage leaves "running" behind forever. Only the
  /// process answers the question the caller is actually asking.
  Future<bool> trampolineAlive() async {
    try {
      final out = await runCommand(
        'pgrep -f "/data/(installer/(scripts/)?)?trampoline.sh" '
        '>/dev/null && echo yes || echo no',
      ).timeout(const Duration(seconds: 10));
      return out.trim().endsWith('yes');
    } catch (_) {
      return false;
    }
  }

  /// The tail of the trampoline's own log, which is the only account of what
  /// happened while the laptop was unplugged.
  Future<String> readTrampolineLogTail({int lines = 40}) async {
    try {
      final out = await runCommand(
        'tail -n $lines /data/installer/trampoline.log 2>/dev/null; true',
      ).timeout(const Duration(seconds: 20));
      return out.trimRight();
    } catch (_) {
      return '';
    }
  }


  Future<void> writeInstallRunState({
    required String runId,
    required String content,
  }) async {
    if (!RegExp(r'^[a-zA-Z0-9._-]+$').hasMatch(runId)) {
      throw ArgumentError.value(runId, 'runId', 'contains unsafe characters');
    }
    final runDir = '$installerHistoryDir/$runId';
    final historyPath = '$runDir/record';
    final historyTemp = '$runDir/.record.tmp';
    final currentTemp = '$installerDir/.run-state.$runId.tmp';
    await runCommand('mkdir -p $runDir');
    await uploadFile(Uint8List.fromList(utf8.encode(content)), historyTemp);
    await runCommand(
      'mv -f $historyTemp $historyPath; '
      'cp $historyPath $currentTemp; '
      'mv -f $currentTemp $installerRunState',
    );
  }
