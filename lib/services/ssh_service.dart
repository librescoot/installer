  /// Probe whether the connected MDB is running a full image with the redis
  /// stack. A minimal/bootstrap rootfs (e.g. flashed by mistake) answers SSH
  /// but ships no redis-cli, so every redis-backed step (the parked-state
  /// gate, the pre-flash lock, the health telemetry) fails with
  /// `redis-cli: not found`. Returns false when redis-cli is absent so the
  /// caller can route straight to re-flash instead of getting wedged.
  /// Which vehicle stack the board is running.
  ///
  /// Null means the board could not answer, which is not the same as
  /// [ServiceStack.none]. It used to be: one `systemctl` that timed out over a
  /// busy link seconds after a reboot was enough to report a finished install
  /// as a rollback to the bootstrap image, with the artifact name and
  /// os-release both saying otherwise. A board that is up but slow gets a few
  /// tries before this gives up on it.
  Future<ServiceStack?> detectServiceStack({int attempts = 12}) async {
    // os-release names the distribution outright, cannot be raced, and is
    // already read on this path. It only settles the stock case: the bootstrap
    // image carries the Librescoot ID too, so a librescoot ID still has to be
    // asked whether the stack is actually there.
    try {
      final id = (await readOsRelease())['ID'] ?? '';
      if (id.isNotEmpty && !id.startsWith('librescoot')) {
        debugPrint('SSH: stack from os-release ID "$id" -> stock');
        return ServiceStack.stock;
      }
    } catch (e) {
      debugPrint('SSH: os-release unreadable, falling back to units: $e');
    }

    for (var attempt = 1; attempt <= attempts; attempt++) {
      try {
        // redis-cli alone separates nothing: the bootstrap image ships valkey
        // so bluetooth-service can run during pairing, and stock ships its own
        // redis with its own schema. The vehicle unit is what every
        // redis-backed step here depends on, and it carries a different name
        // under each stack. Asking for both names is what keeps a healthy
        // stock board distinct from a board with no stack at all.
        final out = await runCommand(stackProbeScript);
        final answer = parseStackProbe(out);
        if (answer != null) {
          // Logged on the way out, not only when it goes wrong. This decides
          // whether a finished install is reported as a failure, and a
          // decision that leaves no trace in the log we ask users for cannot
          // be diagnosed from a report.
          debugPrint('SSH: stack probe -> ${answer.name} (attempt $attempt)');
          return answer;
        }
        debugPrint('SSH: stack probe gave nothing useful: ${out.trim()}');
      } catch (e) {
        debugPrint('SSH: stack probe failed (attempt $attempt): $e');
      }
      if (attempt < attempts) {
        await Future.delayed(const Duration(seconds: 5));
      }
    }
    debugPrint('SSH: stack probe never answered after $attempts attempts');
    return null;
  }

  /// systemd answers list-unit-files with nothing at all for the first minute
  /// or so of a boot, and an empty list looks exactly like a list with no
  /// vehicle unit in it. Emitting `unknown` for that keeps a board that has not
  /// finished starting from being reported as a board with no stack.
  ///
  /// The vehicle unit is `librescoot-vehicle` or `unu-vehicle`.
  /// `vehicle-service` is the binary Librescoot's unit runs, never a unit.
  @visibleForTesting
  static const stackProbeScript =
      r'''command -v redis-cli >/dev/null 2>&1 || { echo none; exit 0; }; '''
      r'''u=$(systemctl list-unit-files 2>/dev/null); '''
      r'''[ -z "$u" ] && { echo unknown; exit 0; }; '''
      r'''echo "$u" | grep -q "^librescoot-vehicle" && { echo librescoot; exit 0; }; '''
      r'''echo "$u" | grep -q "^unu-vehicle" && { echo stock; exit 0; }; '''
      r'''echo none''';

  /// The probe answers with one word. Anything else is not an answer.
  @visibleForTesting
  static ServiceStack? parseStackProbe(String output) {
    final lines = output
        .split('\n')
        .map((l) => l.trim())
        .where((l) => l.isNotEmpty)
        .toList();
    if (lines.isEmpty) return null;
    return switch (lines.last) {
      'librescoot' => ServiceStack.librescoot,
      'stock' => ServiceStack.stock,
      'none' => ServiceStack.none,
      // `unknown` is the board saying it could not answer, which is the same
      // as not answering: null, so the caller retries rather than concluding.
      _ => null,
    };
  }

  /// Wait for a specific vehicle state, polling every [interval].
  /// Returns true if the state was reached, false on timeout.
  Future<bool> waitForVehicleState(
    String targetState, {
    Duration timeout = const Duration(seconds: 120),
    Duration interval = const Duration(seconds: 2),
  }) async {
    final deadline = DateTime.now().add(timeout);
    while (DateTime.now().isBefore(deadline)) {
      final state = await getVehicleState();
      if (state == targetState) return true;
      await Future.delayed(interval);
    }
    return false;
  }

  /// Query scooter health from Redis.
  Future<ScooterHealth> queryHealth() async {
    final health = ScooterHealth();
    health.auxCharge = int.tryParse(
      await redisHget('aux-battery', 'charge') ?? '',
    );
    health.auxVoltageMv = int.tryParse(
      await redisHget('aux-battery', 'voltage') ?? '',
    );
    health.cbbStateOfHealth = int.tryParse(
      await redisHget('cb-battery', 'state-of-health') ?? '',
    );
    health.cbbCharge = int.tryParse(
      await redisHget('cb-battery', 'charge') ?? '',
    );
    // Stock and Librescoot both keep the CBB under this key. `false` is the
    // pack reporting itself absent, which is a different answer from the
    // charge fields being unreadable.
    final cbbPresent = await redisHget('cb-battery', 'present');
    if (cbbPresent == 'true' || cbbPresent == 'false') {
      health.cbbPresent = cbbPresent == 'true';
    }
    // battery-service owns this key and is absent from the bootstrap image, so
    // a missing answer means nobody could say rather than no pack fitted.
    final batteryPresent = await redisHget('battery:0', 'present');
    if (batteryPresent == 'true' || batteryPresent == 'false') {
      health.batteryPresent = batteryPresent == 'true';
    }
    health.batteryCharge = int.tryParse(
      await redisHget('battery:0', 'charge') ?? '',
    );
    return health;
  }

  /// Open the seatbox.
  Future<void> openSeatbox() async {
    await redisLpush('scooter:seatbox', 'open');
  }

  /// Turn the main battery off without touching the seatbox, by telling
  /// battery-service the latch is open. It answers by opening the pack's BMS
  /// contactors, which is electrically what lifting the pack out would do.
  ///
  /// vehicle-service is stopped first because it owns the real latch state and
  /// would re-assert `closed` on its next publish, re-activating the pack
  /// under us. It comes back on the reboot into UMS, which is moments away.
  ///
  /// The value has to be exactly `open` or `closed`: the stock C parser
  /// rejects anything else.
  Future<void> deactivateMainBattery() async {
    await runCommand(
      'systemctl stop unu-vehicle librescoot-vehicle 2>/dev/null; true',
    );
    await runCommand(
      "redis-cli hset vehicle seatbox:lock open >/dev/null && "
      "redis-cli publish vehicle seatbox:lock >/dev/null",
    );
  }

  /// Undo [deactivateMainBattery]. battery-service is what opens and closes the
  /// contactors: it subscribes to `vehicle seatbox:lock` and gates on the hash
  /// field (battery-service service.go:163, reader.go:122), so saying the latch
  /// is closed again is what brings the pack back.
  ///
  /// vehicle-service is restarted because we stopped it, and it owns the real
  /// latch and the dashboard the trampoline later drives. It is not the thing
  /// that switches the pack.
  Future<void> reactivateMainBattery() async {
    await runCommand(
      "redis-cli hset vehicle seatbox:lock closed >/dev/null; "
      "redis-cli publish vehicle seatbox:lock >/dev/null; true",
    );
    await runCommand(
      'systemctl start unu-vehicle librescoot-vehicle 2>/dev/null; true',
    );
  }

  /// Whether the main pack still has its contactors closed. `present` stays
  /// true throughout, because the pack never went anywhere.
  Future<bool> isMainBatteryActive() async {
    final state = await redisHget('battery:0', 'state');
    return state == 'active';
  }

